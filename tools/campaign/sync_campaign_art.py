#!/usr/bin/env python3
"""Copies the main game's campaign art into Warbound.

- Journey paintings (assets/illustrations/journeys/<campaign>.png)
- Chapter briefings (assets/illustrations/<campaign>/<chapter>_briefing.png)

Each one becomes a lossy WebP in spinoff/warbound/assets/campaign_art/, so the spinoff doesn't
carry another 300 MB of PNGs. The journey stops (assets/specs/campaign_journeys.json) and each
campaign's lead hero class (data/campaigns.json heroes[0], mapped as in src/ui/art.gd) go to
data/campaigns/journeys.json.

Run from the repository root or from anywhere:
    python3 spinoff/warbound/tools/campaign/sync_campaign_art.py
Needs Pillow with WebP support.
"""
import os
import json
import re
import sys
from pathlib import Path

from PIL import Image

WB = Path(__file__).resolve().parents[2]
MAIN = Path(os.environ.get("CAERN_MAIN") or sys.exit(
    "Set CAERN_MAIN to a checkout of the main game (github.com/CrownsofCaern/Crowns_of_Caern_4X)."))
OUT = WB / "assets" / "campaign_art"
QUALITY = 78


def lead_classes() -> dict:
    """hero id -> class, from CAMPAIGN_PORTRAIT_CLASSES in the main game's art.gd."""
    src = (MAIN / "src" / "ui" / "art.gd").read_text()
    block = src.split("CAMPAIGN_PORTRAIT_CLASSES := {", 1)[1].split("}", 1)[0]
    return dict(re.findall(r'"(\w+)":\s*"(\w+)"', block))


BRIEFING_WIDTH = 1152  # briefings show at most about 700 px wide; journeys keep full size


def convert(src: Path, dst: Path, width: int = 0) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(src) as im:
        im = im.convert("RGB")
        if width and im.width > width:
            im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
        im.save(dst, "WEBP", quality=QUALITY, method=6)


def main() -> int:
    wb_campaigns = json.loads((WB / "data" / "campaigns" / "campaigns.json").read_text())["campaigns"]
    main_data = json.loads((MAIN / "data" / "campaigns.json").read_text())
    main_campaigns = main_data.get("campaigns", main_data)
    journeys = json.loads((MAIN / "assets" / "specs" / "campaign_journeys.json").read_text())["campaigns"]
    classes = lead_classes()
    out: dict = {"_doc": "Generated by tools/campaign/sync_campaign_art.py from the main game: journey stops "
                 "(campaign_journeys.json) and the lead hero class of each campaign.", "campaigns": {}}
    count = 0
    for cid in wb_campaigns:
        j = journeys.get(cid, {})
        painting = MAIN / "assets" / "illustrations" / "journeys" / f"{cid}.png"
        if painting.exists():
            convert(painting, OUT / "journeys" / f"{cid}.webp")
            count += 1
        hero = (main_campaigns.get(cid, {}).get("heroes") or [""])[0]
        out["campaigns"][cid] = {
            # Warbound's dark elf and fish-men classes drop the main game's de_ / fm_ prefix.
            "lead_class": re.sub(r"^(de|fm)_", "", classes.get(hero, "knight")),
            "nodes": [{"chapter": n["chapter"], "at": n["at"], "layer": n.get("layer", "surface")}
                      for n in j.get("nodes", [])],
        }
        for ch in wb_campaigns[cid]["chapters"]:
            art = MAIN / "assets" / "illustrations" / cid / f"{ch['id']}_briefing.png"
            if art.exists():
                convert(art, OUT / cid / f"{ch['id']}.webp", BRIEFING_WIDTH)
                count += 1
    (WB / "data" / "campaigns" / "journeys.json").write_text(json.dumps(out, indent=1) + "\n")
    print(f"{count} pictures written to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
