#!/usr/bin/env python3
"""Frame each unit sprite's portrait: writes data/unit_portraits.json.

Run from anywhere:  python3 spinoff/warbound/tools/portrait_rects.py
Re-run after sync_from_main.py changes assets/units/.

For every sprite in data/units.json, a square [x, y, size] on the 128x128 sprite that the unit panel
and the build bar show as the unit's portrait. The square may reach past the sprite's edges; the
UI draws that part empty (HudArt.unit_portrait).
* Wide or squat creatures (hounds, drakes, engines): the whole creature, padded and centred.
* Tall ones (soldiers, casters): the upper body, centred on the mass of its upper two thirds,
  so a raised spear or staff does not pull the face off-centre.
"""
import json
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)
# Sprites whose raised spear towers over the head: frame from the head down, tighter.
FROM_HEAD = {"pike_militia", "pike_veteran"}


def head_rect(img: Image.Image, size: int) -> list:
    """A square of the given size from just above the head: the first row at least 14 px wide
    (a spear shaft or blade is narrower), centred on that row band's mass."""
    a = img.getchannel("A")
    px = a.load()
    width, height = img.size
    for top in range(height):
        if sum(1 for x in range(width) if px[x, top] > 128) >= 14:
            break
    n = 0
    sx = 0
    for y in range(top, min(height, top + size)):
        for x in range(width):
            if px[x, y] > 128:
                n += 1
                sx += x
    return [round(sx / n - size / 2), top - 6, size]


def portrait_rect(img: Image.Image) -> list:
    a = img.getchannel("A")
    px = a.load()
    width = img.size[0]
    x0, y0, x1, y1 = a.getbbox()
    w, h = x1 - x0, y1 - y0
    if w >= h * 0.9:
        s = max(w, h) + 6
        return [round((x0 + x1 - s) / 2), round((y0 + y1 - s) / 2), s]
    s = max(80, min(w + 8, 104))
    n = 0
    sx = 0
    for y in range(y0, min(y1, y0 + s * 2 // 3)):
        for x in range(width):
            if px[x, y] > 128:
                n += 1
                sx += x
    cx = sx / n
    return [round(cx - s / 2), y0 - 4, s]


def main() -> int:
    units = json.load(open(os.path.join(PROJECT, "data", "units.json")))["units"]
    rects = {}
    for uid in sorted(units):
        sprite = units[uid]["sprite"].split("/")[-1][:-4]
        if sprite in rects:
            continue
        img = Image.open(os.path.join(PROJECT, "assets", "units", sprite + ".png")).convert("RGBA")
        rects[sprite] = head_rect(img, 72) if sprite in FROM_HEAD else portrait_rect(img)
    lines = ['  "%s": %s' % (k, json.dumps(rects[k])) for k in sorted(rects)]
    with open(os.path.join(PROJECT, "data", "unit_portraits.json"), "w") as f:
        f.write('{\n "_doc": "Generated by tools/portrait_rects.py: portrait square [x, y, size] per unit sprite.",\n')
        f.write(' "rects": {\n' + ",\n".join(lines) + "\n }\n}\n")
    print("framed %d portraits" % len(rects))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
